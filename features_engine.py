# 🌟 重複を防ぐための共通関数
def classify_style(pos):
    """
    最終コーナー通過順位から脚質カテゴリを判定する（学習・推論で完全共通化）
    """
    import pandas as pd
    if pd.isna(pos):
        return '不明'
    pos = float(pos)
    if pos <= 2: return '逃げ'
    elif pos <= 5: return '先行'
    elif pos <= 10: return '差し'
    else: return '追込'
